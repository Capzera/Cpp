#include <bits/stdc++.h>
using namespace std;
long long n, pos, neg, a[100010], diff[100010];
int main() {
	cin >> n;
	for (int i = 1; i <= n; i++) {
		cin >> a[i];
		diff[i] = a[i] - a[i - 1]; // 求差分
		if (i == 1) continue; // 忽略差分数组的第一个元素
		if (diff[i] > 0) pos += diff[i];
		else neg += diff[i];
	}
	cout << max(pos, -neg) << endl << abs(pos + neg) + 1;
	return 0;
}

